import assert from 'node:assert/strict';
import { launch, BASE, shot } from './harness.mjs';
const browser = await launch();
const context = await browser.newContext();
const page = await context.newPage();
const errors = [];
page.on('pageerror', error => errors.push(error.message));
const choice = count => page.getByRole('radio', { name: new RegExp(`^${count === 5 ? 'Quick' : count === 12 ? 'Standard' : 'Extended'} ${count}`) });
const open = async () => { if (await page.locator('.focus-toggle').getAttribute('aria-expanded') !== 'true') await page.locator('.focus-toggle').click(); };
const progress = () => page.locator('.challenge-progress').innerText();
try {
  await page.goto(BASE, { waitUntil: 'networkidle' });
  await open();
  assert.equal(await choice(5).isChecked(), true);
  assert.equal(await choice(12).isEnabled(), true);
  // One-beat practice deliberately allows repeated fragments; the unique-bar
  // capacity limit starts only after switching to full measures.
  assert.equal(await page.getByRole('radio', { name: /one beat/i }).isChecked(), true);
  assert.equal(await choice(20).isEnabled(), true);
  await page.getByRole('radio', { name: /one measure/i }).check();
  assert.equal(await choice(5).isChecked(), true);
  assert.equal(await choice(12).isEnabled(), true);
  assert.equal(await choice(20).isDisabled(), true);
  await choice(12).click();
  assert.match(await page.locator('#challenge-tab').innerText(), /12-question/);
  await page.locator('#challenge-tab').click();
  await page.locator('.answer-choice').first().click();
  const before = await progress(); const questions = await page.locator('.answer-grid').innerText();
  await open(); await choice(5).click();
  await page.getByRole('button', { name: 'Cancel', exact: true }).click();
  assert.equal(await progress(), before); assert.equal(await page.locator('.answer-grid').innerText(), questions);
  assert.equal(await choice(12).isChecked(), true);
  await choice(5).click(); await page.getByRole('button', { name: 'Continue', exact: true }).click();
  assert.match(await progress(), /Question 1 of 5/);
  await open();
  await page.getByLabel(/^Meter/).selectOption('5-4');
  await choice(20).click();
  await page.getByLabel('Save my practice setup').check();
  await page.reload({ waitUntil: 'networkidle' }); await open();
  assert.equal(await choice(20).isChecked(), true);
  assert.match(await page.locator('#challenge-tab').innerText(), /20-question/);
  const saved = await page.evaluate(() => localStorage.getItem('count-it-practice-defaults-v2'));
  await page.goto(BASE + '/?scope=measure&meter=4-4&n=12&pass=10&seed=old-fixed&retry=reseed', { waitUntil: 'networkidle' }); await open();
  assert.equal(await page.getByRole('group', { name: 'Challenge length', exact: true }).count(), 0);
  assert.match(await page.locator('#challenge-tab').innerText(), /12-question/);
  assert.equal(await page.evaluate(() => localStorage.getItem('count-it-practice-defaults-v2')), saved);
  await page.goto(BASE + '/?a=OldDefault&seed=old-default', { waitUntil: 'networkidle' });
  assert.match(await page.locator('#challenge-tab').innerText(), /5-question/);
  await page.goto(BASE, { waitUntil: 'networkidle' }); await open();
  await page.getByLabel(/^Meter/).selectOption('4-4');
  assert.equal(await choice(12).isChecked(), true);
  assert.match(await page.locator('#challenge-tab').innerText(), /12-question/);
  await page.getByLabel(/^Meter/).selectOption('2-4');
  assert.equal(await choice(5).isChecked(), true);
  assert.match(await page.getByRole('group', { name: 'Challenge length', exact: true }).innerText(), /Quick 5 \(4 available\)/);
  assert.match(await page.locator('#challenge-tab').innerText(), /4-question/);
  await page.getByRole('button', { name: 'Reset practice setup', exact: true }).click();
  assert.equal(await choice(5).isChecked(), true);
  assert.equal(await page.getByLabel(/^Meter/).inputValue(), '4-4');
  assert.equal(await page.getByRole('radio', { name: /one beat/i }).isChecked(), true);
  assert.equal(await choice(20).isEnabled(), true);
  assert.equal(JSON.parse(await page.evaluate(() => localStorage.getItem('count-it-practice-defaults-v2'))).challengeLength, 5);
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.getByRole('group', { name: 'Challenge length', exact: true }).scrollIntoViewIfNeeded();
  await shot(page, 'practice-length-phone.png');
  assert.deepEqual(errors, []);
  console.log('PASS length bounds, capacity fallback, cancel/Continue, opt-in persistence, fixed/legacy assignment overrides, reset and phone layout');
} finally { await browser.close(); }
